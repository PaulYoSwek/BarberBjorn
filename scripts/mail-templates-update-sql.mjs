// SQL that moves stored mail templates from an older version of src/mail-templates.ts
// to the current one, only where Bjorn has not edited them.
// Usage: node scripts/mail-templates-update-sql.mjs previous-templates.json > supabase/migrations/<stamp>_mail_templates.sql
import { readFileSync } from 'node:fs'
import { MAIL_TEMPLATES } from '../src/mail-templates.ts'

const previous = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const q = (text) => `'${text.replaceAll("'", "''")}'`
const lines = ['-- Generated by scripts/mail-templates-update-sql.mjs from src/mail-templates.ts.']
for (const [key, langs] of Object.entries(MAIL_TEMPLATES)) {
  for (const [lang, { subject, body }] of Object.entries(langs)) {
    const old = previous[key]?.[lang]
    lines.push(
      `insert into mail_templates (key, lang, subject, body) values (${q(key)}, ${q(lang)}, ${q(subject)}, ${q(body)})`,
      `  on conflict (key, lang) do nothing;`,
    )
    if (old) {
      lines.push(
        `update mail_templates set subject = ${q(subject)}, body = ${q(body)}`,
        `  where key = ${q(key)} and lang = ${q(lang)} and subject = ${q(old.subject)} and body = ${q(old.body)};`,
      )
    }
  }
}
process.stdout.write(lines.join('\n') + '\n')
