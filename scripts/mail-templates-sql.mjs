// Writes the SQL that stores the starting mail templates (node scripts/mail-templates-sql.mjs).
// Old seed texts that Bjorn never edited are replaced; edited ones are left alone.
import { MAIL_TEMPLATES } from '../src/mail-templates.ts'

const OLD = {
  thanks: { nl: 'Hoi {{name}}, je {{service}} staat op {{date}} om {{time}}. Tot dan. Bjorn', en: 'Hi {{name}}, your {{service}} is on {{date}} at {{time}}. See you then. Bjorn' },
  accepted: { nl: 'Hoi {{name}}, je {{service}} op {{date}} om {{time}} is bevestigd. Bjorn', en: 'Hi {{name}}, your {{service}} on {{date}} at {{time}} is confirmed. Bjorn' },
  declined: { nl: 'Hoi {{name}}, {{date}} om {{time}} lukt niet. Mail of bel voor een andere tijd. Bjorn', en: 'Hi {{name}}, {{date}} at {{time}} is not possible. Mail or call for another time. Bjorn' },
}
const q = (text) => `'${text.replaceAll("'", "''")}'`
const lines = ['-- Generated by scripts/mail-templates-sql.mjs from src/mail-templates.ts.']
for (const [key, langs] of Object.entries(MAIL_TEMPLATES)) {
  for (const [lang, { subject, body }] of Object.entries(langs)) {
    lines.push(
      `insert into mail_templates (key, lang, subject, body) values (${q(key)}, ${q(lang)}, ${q(subject)}, ${q(body)})`,
      `  on conflict (key, lang) do update set subject = excluded.subject, body = excluded.body` +
        (OLD[key] ? `\n  where mail_templates.body = ${q(OLD[key][lang])};` : `\n  where false;`),
    )
  }
}
process.stdout.write(lines.join('\n') + '\n')
